'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { installMicrophoneGate } = require('../dist/microphoneGate.js');
const { installMicrophoneGateControls } = require('../dist/microphoneGateControls.js');
const { MICROPHONE_GATE_MODULE_URL } = require('../dist/microphoneGateProtocol.js');

// Sandboxed Electron preloads cannot require sibling CommonJS modules. Inline
// the compiled, self-contained renderer functions into a dedicated preload so
// its only runtime import is Electron's supported sandbox bridge.
const source = `// Generated by scripts/buildMicrophoneGatePreload.cjs; do not edit.\n
'use strict';
const { contextBridge } = require('electron');
try {
  contextBridge.executeInMainWorld({
    func: function () {
      if (window !== window.top || !['http:', 'https:'].includes(location.protocol)) return;
      try {
        (${installMicrophoneGate.toString()})(${JSON.stringify(MICROPHONE_GATE_MODULE_URL)});
      } catch (error) {
        console.warn('[microphone-gate] Could not initialize microphone processing:', error);
      }
      const controls = function () {
        try {
          (${installMicrophoneGateControls.toString()})();
        } catch (error) {
          console.warn('[microphone-gate] Could not initialize microphone controls:', error);
        }
      };
      if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', controls, { once: true });
      else controls();
    }
  });
} catch (error) {
  console.warn('[microphone-gate] Could not install desktop microphone support:', error);
}
`;

fs.writeFileSync(path.join(__dirname, '../dist/microphoneGatePreload.js'), source, 'utf8');
